-- Path joining helper compatible with Windows and forward slashes
local function joinPath(dir, filename)
  local clean_dir = tostring(dir):gsub("[/\\]+$", "")
  local sep = clean_dir:find("\\") and "\\" or "/"
  return clean_dir .. sep .. filename
end

